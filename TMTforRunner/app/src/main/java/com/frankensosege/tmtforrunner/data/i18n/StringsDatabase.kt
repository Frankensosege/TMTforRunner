package com.frankensosege.tmtforrunner.data.i18n

import android.content.Context
import androidx.room.*

// ─── Entity ───────────────────────────────────────────────
@Entity(tableName = "app_strings", primaryKeys = ["languageCode", "stringKey"])
data class StringEntity(
    val languageCode: String,
    val stringKey: String,
    val value: String
)

// ─── DAO ──────────────────────────────────────────────────
@Dao
interface StringsDao {
    @Query("SELECT * FROM app_strings WHERE languageCode = :lang")
    suspend fun getStrings(lang: String): List<StringEntity>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertAll(strings: List<StringEntity>)

    @Query("SELECT COUNT(*) FROM app_strings WHERE languageCode = :lang")
    suspend fun countForLanguage(lang: String): Int
}

// ─── Database ─────────────────────────────────────────────
@Database(entities = [StringEntity::class], version = 7, exportSchema = false)
abstract class StringsDatabase : RoomDatabase() {
    abstract fun stringsDao(): StringsDao

    companion object {
        @Volatile private var INSTANCE: StringsDatabase? = null

        fun getInstance(context: Context): StringsDatabase =
            INSTANCE ?: synchronized(this) {
                Room.databaseBuilder(
                    context.applicationContext,
                    StringsDatabase::class.java,
                    "tmt_strings_db"
                )
                    .fallbackToDestructiveMigration()
                    .build().also { INSTANCE = it }
            }
    }
}

